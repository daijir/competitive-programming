"""
【問題の整理と分解（Divide and Conquer / 問題の要素分解）】
この問題を一度に解こうとせず、4つの小さなステップ（部分問題）に分解して考えます。

Step 1: 入力を受け取って扱いやすい形にする
  - 1行目: 天気予報の日数 D (整数)
  - 2行目: 各日の天気の並び w (整数のリスト: [w_0, w_1, ..., w_{D-1}])

Step 2: 「虹が見える条件」を論理式にする
  - 対象とする日: i 日後 (i は 1 から D-1 まで)
  - ※ 0日後（今日）は前日のデータがないため調べる必要はありません
  - 条件: 「前日 (i-1 日後) が 雨(2)」 かつ 「当日 (i 日後) が 晴れ(0)」
    => w[i - 1] == 2 and w[i] == 0

Step 3: ループで全日程を探索し、条件に合う日を収集する
  - 該当する日を記録するための空リストを用意する (例: ans = [])
  - i = 1 から D-1 まで順番にチェックし、条件を満たしたら ans に i を追加する

Step 4: 結果の出力（分岐処理）
  - 1日も見つからなかった場合 (ans が空): -1 を出力
  - 1日以上見つかった場合: スペース区切りで出力 (例: 1 4)

==================================================

【解くために必要な考え方】
1. インデックスの相対関係（当日と前日）:
   - 当日を i と置くと、前日は必ず i - 1 と表せます。
   - リストの外側を参照してエラー（IndexError）にならないよう、探索範囲は 1 から D-1 にします。
2. 該当なしの例外処理:
   - 「該当する日がない場合は -1」という仕様を見落とさず、結果リストが空かどうかの判定を入れます。

==================================================

【必要なPythonの基礎知識】
1. 標準入力の取得とリスト化:
   - 1行目の整数を取得:
       D = int(input())
   - 2行目の空白区切り数値を整数のリストとして取得:
       w = list(map(int, input().split()))
       * input().split(): スペースで区切って文字列のリストにする ['2', '0', '1', ...]
       * map(int, ...): リスト内の各文字を数値型に変換する
       * list(...): リストとして確定させる [2, 0, 1, ...]

2. ループ処理 (for文 と range):
   - 1 から D-1 まで繰り返す:
       for i in range(1, D):

3. 条件分岐 (if文 と 論理積 and):
   - 前日が雨(2) かつ 当日が晴れ(0):
       if w[i - 1] == 2 and w[i] == 0:

4. リストの操作:
   - リストへの追加:
       ans.append(i)
   - リストが空かどうかの判定:
       if len(ans) == 0:  (または if not ans:)

5. リストの空白区切り出力:
   - リストの中身を半角スペース区切りで1行出力する方法:
       print(*ans)
       * アスタリスク (*) を付けると、リストの中身を展開（アンパック）して渡せます。
       * 例: ans = [1, 4] のとき print(*ans) は print(1, 4) と同じになり、自動的にスペース区切りで出力されます。
"""

D = int(input())
w = list(map(int, input().split()))

ans = []

for i in range(1, D):
    if w[i-1] == 2 and w[i] == 0:
        ans.append(i)

if len(ans) == 0:
    print(-1)
else:
    print(*ans)